    async def locate(self, target, img):
        """Where `target` is in a picture of a window, for a click nothing else could find (computer.find): Jev's Box, asked beside whether
        the thing is there at all (a Box always answers a box: TypeSafe's own advice), then a second look at only that part of the picture,
        because a box can be sure and wrong (2026-10-17, live: “Don't save” boxed over “Cancel” at 0.77). -> {"point": its centre in the
        original picture's pixels, or None unless all three agree, "seen", "box", "confidence", "check"}, or None when Jev couldn't look."""
        import math

        from typesafe_sdk import Box, Image, Noul
        fitted, scale, size = fit(img)
        r = await self.look({"window": Image.from_pil(fitted, format="png")},
                            {"seen": Noul(instructions=f"Is there a control or item that a person would call “{target}” in the picture `window`?"),
                             "where": Box(instructions=f"the control or item called “{target}” in `window`")})
        a = r.get("answers") or {}
        if r["status"] != "ok" or "where" not in a:
            return None
        out = {"seen": (a.get("seen") or {}).get("noul"), **a["where"], "check": None,
               "point": box_point(a["where"]["box"], fitted.size, scale, size), "rect": box_rect(a["where"]["box"], fitted.size, scale)}
        if out["point"] is None or (out["seen"] or 0) < SEEN_TRUST or out["confidence"] < BOX_TRUST:
            return {**out, "point": None}
        b, (w, h) = out["box"], fitted.size
        part = fitted.crop((int(b["left"] * w), int(b["top"] * h), max(int(b["left"] * w) + 1, math.ceil(b["right"] * w)),
                            max(int(b["top"] * h) + 1, math.ceil(b["bottom"] * h))))
        c = await self.look({"part": picture(part)},
                            {"is": Noul(instructions=f"`part` is a piece cut out of a window. Is it the control or item a person would call “{target}”, "
                                                     "and not a different one beside it or only a piece of one?")})
        out["check"] = ((c.get("answers") or {}).get("is") or {}).get("noul") if c["status"] == "ok" else None
        return out if (out["check"] or 0) >= SEEN_TRUST else {**out, "point": None}

    async def which_known(self, img, known):
        """Which of the things the owner taught by sight (core/vision.py: {label: picture}) is in the photo, by Jev's comparison with their
        own pictures, or "none". -> (label | None, confidence) or (None, None) when Jev couldn't look."""
        from typesafe_sdk import Choice
        crit = {f"k{i}": {"thing": label, "looks_like": picture(p)} for i, (label, p) in enumerate(known.items(), 1)}
        crit["none"] = "Something else, or none of these things."
        r = await self.look({"photo": picture(img)}, {"which": Choice(instructions="Which of these things of the owner's is in `photo`, the same "
                                                                                  "object as in its picture (not just the same kind)?", criteria=crit)})
        a = (r.get("answers") or {}).get("which")
        if r["status"] != "ok" or not a:
            return None, None
        pick = a["choice"]
        return (None if pick == "none" else crit[pick]["thing"]), a["confidence"]

