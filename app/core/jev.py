def write_env(name, value, path=ROOT / ".env"):
    """Put NAME=value into Monday/.env (the owner pasting a key in Connections, 2026-10-13): an existing line, even a commented placeholder
    `# NAME=…`, is replaced in place, else the line is appended. Only names Monday knows (ENV_KEYS); the value is never logged or returned."""
    if name not in ENV_KEYS:
        raise ValueError(f"{name} isn't a key Monday uses.")
    value = (value or "").strip()
    if not value or re.search(r"[\r\n]", value) or len(value) > 500:
        raise ValueError("That doesn't look like a key.")
    lines = path.read_text(encoding="utf-8-sig").splitlines() if path.exists() else []
    out, done = [], False
    for line in lines:
        if not done and re.match(rf"^\s*#?\s*{re.escape(name)}\s*=", line):
            out.append(f"{name}={value}")
            done = True
        else:
            out.append(line)
    if not done:
        out.append(f"{name}={value}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return name


def setting(name, file_vals=None):
    """A Jev setting: the real environment first, then Monday/.env. Never exported or logged."""
    return (os.environ.get(name) or "").strip() or (read_env_file() if file_vals is None else file_vals).get(name)


def resolve_key():
    file_vals = read_env_file()
    for name in ("TYPESAFE_API_KEY", "JEV_API_KEY"):
        v = setting(name, file_vals)
        if v:
            return v, name
    return None, None


