    def _finish(self, d):
        if d["status"] in ("ok", "timeout", "error"):
            self._recent = (self._recent + [d["status"] == "ok"])[-RECENT_WINDOW:]
        if d["status"] == "ok" and self._health and self._health["status"] != "online":
            # A live answer is the best health check there is: show Jev online now, not at the next probe.
            self._health = {**self._health, "status": "online", "detail": "Answered a routing decision just now.",
                            "checked_at": time.time()}
            self._health_at = time.monotonic()
        self.last = d
        return d

    # -- health ---------------------------------------------------------------------------------
    async def health(self, force=False):
        """ONLINE only after a verified call; DEGRADED on recent failures; OFFLINE when unreachable or rejected."""
        if not force and self._health and time.monotonic() - self._health_at < JEV_HEALTH_TTL_S:
            return self._apply_recent(self._health)
        key, source = resolve_key()
        if not key:
            h = {"status": "not_configured", "detail": "No Jev key. Add TYPESAFE_API_KEY to Monday/.env or the environment."}
        else:
            client = self._get_client()
            from typesafe_sdk import (TypeSafeAPIConnectionError, TypeSafeAPIError, TypeSafeAPITimeoutError,
                                      TypeSafeAuthenticationError, TypeSafePermissionDeniedError)
            for attempt in (1, 2):  # one retry: a single slow or dropped probe must not flip the pill
                t0 = time.perf_counter()
                try:
                    models = await asyncio.wait_for(client.models.list(timeout=JEV_HEALTH_TIMEOUT_S), JEV_HEALTH_TIMEOUT_S + 0.5)
                    h = {"status": "online", "latency_ms": round((time.perf_counter() - t0) * 1000, 1),
                         "models": [m.name for m in models.models], "detail": "API reachable, key accepted."}
                    break
                except (TypeSafeAuthenticationError, TypeSafePermissionDeniedError) as e:
                    h = {"status": "offline", "detail": f"The Jev API key was rejected ({e.status})."}
                    break
                except TypeSafeAPIError as e:  # it answered, but badly: rate limit, overload, server error
                    h = {"status": "degraded" if e.status in (429, 529) or e.status >= 500 else "offline",
                         "detail": f"Jev API error {e.status}."}
                    break
                except (asyncio.TimeoutError, TypeSafeAPITimeoutError):  # before ConnectionError: it subclasses it
                    h = {"status": "degraded", "detail": f"Jev was slow to answer a health check (over {JEV_HEALTH_TIMEOUT_S:g} s)."}
                except (TypeSafeAPIConnectionError, OSError) as e:
                    h = {"status": "offline", "detail": f"Jev API unreachable ({type(e).__name__})."}
                except Exception as e:  # the pill must never take Monday down
                    h = {"status": "offline", "detail": f"Jev health check failed ({type(e).__name__})."}
        h |= {"configured": bool(key), "key_source": source, "model": setting("TYPESAFE_DEFAULT_MODEL") or "jev-latest",
              "timeout_ms": int(JEV_TIMEOUT_S * 1000), "question_set": QUESTION_SET, "checked_at": time.time()}
        self._health, self._health_at = h, time.monotonic()
        return self._apply_recent(h)

    def _apply_recent(self, h):
        if h["status"] == "online" and len(self._recent) >= 3:
            fail_rate = self._recent.count(False) / len(self._recent)
            if fail_rate >= DEGRADED_FAILURE_RATE:
                return {**h, "status": "degraded", "detail": f"{fail_rate:.0%} of the last {len(self._recent)} decisions failed."}
        return h


