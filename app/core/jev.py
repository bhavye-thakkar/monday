def parse(resp, projects):
    """SDK response -> plain dict. Raises KeyError/AttributeError if an expected answer is missing."""
    c, n, s = resp.choices, resp.nouls, resp.scores
    intent = c["intent"]
    out = {
        "intent": intent.choice, "confidence": round(intent.confidence, 4),
        "intent_probabilities": {k: round(v, 4) for k, v in intent.probabilities.items()},
        "complexity": round(s["complexity"].score, 3), "complexity_confidence": round(s["complexity"].confidence, 4),
        "destructive": round(n["destructive"].noul, 4),
        "task_action": c["task_action"].choice, "task_action_confidence": round(c["task_action"].confidence, 4),
        "calendar_action": c["calendar_action"].choice,
        "system_action": c["system_action"].choice, "system_action_confidence": round(c["system_action"].confidence, 4),
        "tool": c["tool"].choice, "tool_confidence": round(c["tool"].confidence, 4), "remember": round(n["remember"].noul, 4),
        "needs_llm": round(n["needs_llm"].noul, 4),  # "model" in a decision is the Jev model that answered
        "model_class": c["model_class"].choice, "model_class_confidence": round(c["model_class"].confidence, 4),
        "verify": round(n["verify"].noul, 4),
        "voice_action": c["voice_action"].choice, "voice_action_confidence": round(c["voice_action"].confidence, 4),
        "power_action": c["power_action"].choice if "power_action" in c else None,
        "power_action_confidence": round(c["power_action"].confidence, 4) if "power_action" in c else None,
        "follow_up": round(n["follow_up"].noul, 4) if "follow_up" in n else None,
        "project": None, "project_confidence": None,
        # v9: the first move, a correction, an unclear thing, the tone (each gated in code: ACTION_SURE, REDO_P, ASK_P; tone is never a gate)
        "action": c["action"].choice, "action_confidence": round(c["action"].confidence, 4),
        "redo": round(n["redo"].noul, 4), "ambiguous": round(n["ambiguous"].noul, 4),
        "tone": c["tone"].choice, "tone_confidence": round(c["tone"].confidence, 4),
        "file": round(n["file"].noul, 4) if "file" in n else None,  # v10: the answer as a document too (monday.DOC_FILE_P)
    }
    if projects and "project" in c:
        p = c["project"]
        out["project"] = None if p.choice == "none" else p.choice
        out["project_confidence"] = round(p.confidence, 4)
    # v5: the always-asked three by name, and every live answer as asked (`live`: what this moment's questions said)
    for k in ("speech_kind", "browser_kind"):
        if k in c:
            out[k], out[f"{k}_confidence"] = c[k].choice, round(c[k].confidence, 4)
    if "needs_vision" in n:
        out["needs_vision"] = round(n["needs_vision"].noul, 4)
    out["live"] = {k: {"choice": v.choice, "confidence": round(v.confidence, 4)} for k, v in c.items()
                   if k not in FIXED and k not in ("speech_kind", "browser_kind")}
    out["live"] |= {k: {"noul": round(v.noul, 4)} for k, v in n.items() if k not in FIXED and k != "needs_vision"}
    return out


