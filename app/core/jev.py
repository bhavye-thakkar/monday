def live_state(ctx):
    """The state the live questions read, under the names they use (the ready agents replace the fixed list when they are known)."""
    ctx, out = ctx or {}, {}
    for k, n in (("windows", CTX_MAX), ("apps", CTX_MAX), ("clauses", DEPENDS_MAX + 1)):
        if ctx.get(k):
            out[k] = list(ctx[k])[:n]
    if ctx.get("tasks"):
        out["tasks"] = [{"title": t["title"], "status": t["status"]} for t in ctx["tasks"][:CTX_MAX]]
    if ctx.get("agents"):
        out["agents"] = [f"{a['name']}: {a['does']}" for a in ctx["agents"][:CTX_MAX]]
    if ctx.get("browser"):
        out["browser"] = ctx["browser"]
    if ctx.get("offer"):
        out["offer"] = ctx["offer"]
    return out


