def fit(img):
    """Any picture Monday has (a PIL image, an RGB array from core/vision.py, a file's path or its bytes) within the API's limits: its longest
    side at most IMG_MAX, each side at least IMG_MIN (a small one padded at its right and bottom, never stretched, so its top-left stays
    put). -> (the RGB PIL image, the scale from the original's pixels to its)."""
    import io

    from PIL import Image as PImage
    if isinstance(img, (str, Path)):
        img = PImage.open(img)
    elif isinstance(img, (bytes, bytearray)):
        img = PImage.open(io.BytesIO(img))
    elif not isinstance(img, PImage.Image):
        img = PImage.fromarray(img)
    img, scale = img.convert("RGB"), 1.0
    size = img.size
    if max(img.size) > IMG_MAX:
        scale = IMG_MAX / max(img.size)
        img = img.resize((max(1, round(img.width * scale)), max(1, round(img.height * scale))), PImage.LANCZOS)
    if min(img.size) < IMG_MIN:
        canvas = PImage.new("RGB", (max(img.width, IMG_MIN), max(img.height, IMG_MIN)), (0, 0, 0))
        canvas.paste(img, (0, 0))
        img = canvas
    return img, scale, size


def picture(img):
    """A picture as a TypeSafe Image (PNG: screens are text, and JPEG blurs it), fitted to the limits."""
    from typesafe_sdk import Image
    return Image.from_pil(fit(img)[0], format="png")


def box_point(box, fitted, scale, size):
    """The centre of a Box answer (fractions of the fitted picture) in the original picture's pixels, or None when it fell in fit()'s
    padding (so not on the window at all)."""
    x, y = (box["left"] + box["right"]) / 2 * fitted[0] / scale, (box["top"] + box["bottom"]) / 2 * fitted[1] / scale
    return (round(x), round(y)) if 0 <= x < size[0] and 0 <= y < size[1] else None


def box_rect(box, fitted, scale):
    """A Box answer as (left, top, right, bottom) in the original picture's pixels: the whole of it, for Monday's marks."""
    return tuple(round(v) for v in (box["left"] * fitted[0] / scale, box["top"] * fitted[1] / scale, box["right"] * fitted[0] / scale,
                                     box["bottom"] * fitted[1] / scale))


