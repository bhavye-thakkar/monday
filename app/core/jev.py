async def _repair_drill():
    """python -m core.jev --repair: Jev's read of real failures against REPAIR_BUG_MIN / REPAIR_AGENT_MIN. What matters is that no
    "owner" failure is acted on; a bug or a stuck agent that is missed only means nothing extra happens."""
    svc = JevService()
    health = await svc.health(force=True)
    print(f"jev health: {health['status']} ({health.get('detail')}) model={health.get('model')}")
    if health["status"] not in ("online", "degraded"):
        return
    await svc.prepass("warm up the connection", "Monday")
    acted_wrongly = missed = 0
    print(f"gates: monday_bug >= {REPAIR_BUG_MIN:.2f} starts a coding agent; other_agent >= {REPAIR_AGENT_MIN:.2f} hands the request over\n"
          f"{'bug':>5} {'other':>5} {'owner':>5} {'ms':>5}  acts      should    error")
    for request, worker, error, should in REPAIR_DRILL:
        r = await svc.diagnose(request, error, worker)
        if r["status"] != "ok":
            print(f"  {r['status']}: {r['error']}  {error[:60]!r}")
            continue
        p = r["answers"]["cause"]["probabilities"]
        acts = ("monday_bug" if r["choice"] == "monday_bug" and r["confidence"] >= REPAIR_BUG_MIN else
                "other_agent" if r["choice"] == "other_agent" and r["confidence"] >= REPAIR_AGENT_MIN else "nothing")
        bad = acts != "nothing" and acts != should
        acted_wrongly += bad
        missed += acts == "nothing" and should != "owner"
        print(f"{p.get('monday_bug', 0):5.2f} {p.get('other_agent', 0):5.2f} {p.get('owner', 0):5.2f} {r['latency_ms']:5.0f}  {acts:<9} {should:<9} "
              f"{'BAD ' if bad else ''}{error[:70]!r}")
    print(f"started something it shouldn't have: {acted_wrongly} of {len(REPAIR_DRILL)} · did nothing where an agent could have helped: {missed}")
    await svc.aclose()


async def _drill():
    svc = JevService()
    health = await svc.health(force=True)
    print(f"jev health: {health['status']} ({health.get('detail')}) model={health.get('model')}")
    if health["status"] not in ("online", "degraded"):
        return
    await svc.prepass("warm up the connection", "Monday")  # the first call pays the TLS handshake
    rows = []
    print(f"gates: addressed >= {ADDRESSED_FILMING:.2f} and narrating < {NARRATING_QUIET:.2f} answers; the assistant is called Monday\n"
          f"{'addr':>5} {'narr':>5} {'done':>5} {'risk':>5} {'ms':>5}  verdict  said")
    for line, should in DRILL:
        r = await svc.prepass(line, "Monday", filming=True)
        if r["status"] != "ok":
            print(f"  {r['status']}: {r['error']}  {line!r}")
            continue
        n, verdict = r["numbers"], gate(r["numbers"])[0]
        rows.append((should, n, verdict))
        print(f"{n['addressed']:5.2f} {n['narrating']:5.2f} {n['complete']:5.2f} {n['stakes']:5.2f} {r['latency_ms']:5.0f}  {verdict:<7}  "
              f"{'ask ' if should else 'talk'} {line!r}")
    talk, asks = [r for r in rows if not r[0]], [r for r in rows if r[0]]
    answered, missed = sum(v == "answer" for _, _, v in talk), sum(v != "answer" for _, _, v in asks)
    print(f"narration that would be answered: {answered} of {len(talk)} · asks that would be missed: {missed} of {len(asks)}")
    if (answered or missed) and talk and asks:
        hi, lo = max(n["addressed"] for _, n, _ in talk), min(n["addressed"] for _, n, _ in asks)
        print(f"addressed: narration tops out at {hi:.2f}, asks bottom out at {lo:.2f}: " + (
            f"a gate near {(hi + lo) / 2:.2f} separates them" if hi < lo else "no single gate separates them; read the narrating column first"))
    print(f"\njudge: a chat answer is blocked at claims >= {CLAIM:.2f} (chat has no receipts, so no claim is backed)")
    wrong = 0
    for question, answer, should in JUDGE_DRILL:
        r = await svc.judge(question, answer)
        c = r["numbers"].get("claims")
        blocked = r["status"] == "ok" and c is not None and c >= CLAIM
        wrong += blocked != should
        print(f"  claims {c if c is None else format(c, '.2f')}  {'BLOCKED' if blocked else 'passes '}  "
              f"{'ok ' if blocked == should else 'BAD'} {r['latency_ms'] or 0:.0f} ms  {answer!r}")
    print(f"judge misfires: {wrong} of {len(JUDGE_DRILL)}")
    await svc.aclose()


