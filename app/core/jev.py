def read_env_file(path=ROOT / ".env"):
    """KEY=VALUE pairs from Monday/.env (comments and empty values ignored). Nothing is exported or logged."""
    out = {}
    try:
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                v = v.strip().strip('"').strip("'")
                if k.strip() and v:
                    out[k.strip()] = v
    except OSError:
        pass
    return out


