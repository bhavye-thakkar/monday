def live_questions(ctx):
    """The questions this moment calls for (v5, the owner: "the questions to Jev should be dynamic and always change"): built from what
    is on the computer now, so they differ from one request to the next. ctx (Monday.jev_context): `windows`, `tasks`, `apps`, `agents`,
    `browser`, `clauses`, each also put in the state under the same name. Options are keys for code ("w1", the task's id…); the words
    are what Jev reads. Each has a "none" way out: the thing may not be there."""
    from typesafe_sdk import Choice, Noul
    q, ctx = {}, ctx or {}
    if ctx.get("windows"):
        crit = {f"w{i}": f"The open window `windows[{i}]`: {w}" for i, w in enumerate(ctx["windows"][:CTX_MAX])}
        q["window"] = Choice(instructions="Which open window in `windows` does `request` mean ('close it', 'type in this', 'the "
                                          "calculator'), if it means one?", criteria=crit | {"none": "No open window in particular."})
    if ctx.get("tasks"):
        crit = {t["id"]: f"The task `tasks[{i}]`: {t['title']} ({t['status']})" for i, t in enumerate(ctx["tasks"][:CTX_MAX])}
        q["task_ref"] = Choice(instructions="Which of Monday's tasks in `tasks` does `request` ask about or act on, if any?",
                               criteria=crit | {"none": "None of these tasks."})
    if ctx.get("apps"):
        crit = {f"a{i}": f"The app called {a}" for i, a in enumerate(ctx["apps"][:CTX_MAX])}
        q["app"] = Choice(instructions="Which installed app in `apps` does `request` mean, if it names one (even misheard)?",
                          criteria=crit | {"none": "None of these apps."})
    if ctx.get("agents"):
        crit = {a["key"]: f"{a['name']}: {a['does']}" for a in ctx["agents"][:CTX_MAX]}
        q["agent"] = Choice(instructions="Which of the agents ready in `agents` should carry out `request`, if it needs one?",
                            criteria=crit | {"none": "No agent: Monday's own tools or a reply in words."})
